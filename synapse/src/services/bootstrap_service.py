"""Bootstrap service — self-contained setup script + JSON manifest generation.

Two output modes:
- ``format=sh`` (default): return a bash script for ``curl ... | bash``
- ``format=json``: return a JSON file manifest for AI self-bootstrap
"""

from __future__ import annotations

from pathlib import Path

TEMPLATES_DIR = Path(__file__).resolve().parent.parent.parent / "docs" / "templates"


def _load_skill_md() -> str:
    """Load the canonical thin-protocol SKILL.md template."""
    path = TEMPLATES_DIR / "synapse-client" / "SKILL.md"
    return path.read_text(encoding="utf-8")


def _load_script(name: str) -> str:
    """Load a runtime script from the synapse-client scripts directory."""
    path = TEMPLATES_DIR / "synapse-client" / "scripts" / name
    return path.read_text(encoding="utf-8")


_SCRIPT_NAMES = [
    "session-init.js",
    "api-client.js",
    "keychain.js",
    "heartbeat.js",
    "ws-daemon.js",
]


def _build_env_content(
    *,
    api_base_url: str,
    api_key: str,
    worker_id: str,
    project_id: str,
    role: str = "builder",
    use_keychain: bool = True,
) -> str:
    """Build .env file content with live credentials.

    P11-B35 (Key 隔离): When use_keychain=True, omits SYNAPSE_API_KEY
    from the .env file. The key is stored in OS keychain instead,
    preventing cross-Worker key impersonation on shared filesystems.
    .env retains the keychain reference for session bootstrap.

    P11-B106 PFL-104: SYNAPSE_WORKER_ROLE added to support
    session-init.js role detection.
    """
    lines = [
        "# Synapse Worker 环境配置 (auto-generated by bootstrap)",
        f"SYNAPSE_API_URL={api_base_url}",
        f"SYNAPSE_WORKER_ID={worker_id}",
        f"SYNAPSE_PROJECT_ID={project_id}",
        f"SYNAPSE_WORKER_ROLE={role}",
    ]

    if use_keychain:
        # Key stored in OS keychain, not plaintext on disk (P-045 / B35)
        lines.append(
            f"# SYNAPSE_API_KEY stored in OS keychain — "
            f"run: synapse-key.sh get {worker_id}"
        )
        lines.append(
            f"SYNAPSE_KEYCHAIN_ITEM=synapse-worker-{worker_id}"
        )
    else:
        # Legacy fallback — plaintext key in .env (not recommended)
        lines.append(f"SYNAPSE_API_KEY={api_key}")

    return "\n".join(lines) + "\n"


# ── format=sh: bash script builder ──────────────────────────────────────────


def build_bootstrap_sh(
    *,
    worker_id: str,
    project_id: str,
    api_base_url: str,
    api_key: str,
    role: str,
    client: str = "auto",
    use_keychain: bool = True,
) -> str:
    """Build a self-contained bash bootstrap script.

    The script auto-detects the AI client type, writes SKILL.md and .env
    to the correct paths, stores the API key in OS keychain (P11-B35),
    and calls handshake to verify connectivity.

    P11-B35: When use_keychain=True, the .env file excludes the plaintext
    API key; the key is stored in macOS Keychain / Linux Secret Service.
    """
    skill_md = _load_skill_md()
    env_content = _build_env_content(
        api_base_url=api_base_url,
        api_key=api_key,
        worker_id=worker_id,
        project_id=project_id,
        role=role,
        use_keychain=use_keychain,
    )

    # Override client detection when explicit
    client_detection = _CLIENT_DETECTION_BLOCK
    if client != "auto":
        client_detection = f'    CLIENT="{client}"  # server-specified\n'

    # Keychain storage step (P11-B35)
    keychain_section = _build_keychain_section(
        worker_id=worker_id, api_key=api_key, use_keychain=use_keychain
    )

    return f"""#!/usr/bin/env bash
# Synapse Worker Bootstrap — auto-generated
# Worker: {worker_id} · Project: {project_id} · Role: {role}
set -euo pipefail

# ── Config ──
SYNAPSE_API_URL="{api_base_url}"
SYNAPSE_API_KEY="{api_key}"
SYNAPSE_WORKER_ID="{worker_id}"
SYNAPSE_PROJECT_ID="{project_id}"
SYNAPSE_ROLE="{role}"

# ── Color helpers ──
GREEN='\\033[0;32m'
RED='\\033[0;31m'
YELLOW='\\033[1;33m'
BLUE='\\033[0;34m'
NC='\\033[0m'

echo ""
echo "┌──────────────────────────────────────────┐"
echo "│  Synapse Worker Bootstrap                │"
echo "│  Worker: {worker_id[:20]}...  │"
echo "│  Project: {project_id[:20]}...  │"
echo "└──────────────────────────────────────────┘"
echo ""

# ── Detect client type ──
{client_detection}
echo "${{BLUE}}▎ 客户端类型: ${{CLIENT}}${{NC}}"

# ── Write SKILL.md ──
write_skill() {{
    case "${{CLIENT}}" in
        claude)
            SKILL_DIR=".claude/skills/synapse"
            SKILL_PATH="${{SKILL_DIR}}/SKILL.md"
            mkdir -p "${{SKILL_DIR}}"
            ;;
        codex)
            SKILL_DIR=".agents/skills/synapse"
            SKILL_PATH="${{SKILL_DIR}}/SKILL.md"
            mkdir -p "${{SKILL_DIR}}"
            ;;
        cursor)
            SKILL_DIR=".cursor/rules"
            SKILL_PATH="${{SKILL_DIR}}/synapse-worker.mdc"
            mkdir -p "${{SKILL_DIR}}"
            ;;
        *)
            echo "${{RED}}❌ 未知客户端: ${{CLIENT}} (支持 claude | codex | cursor)${{NC}}"
            exit 1
            ;;
    esac

    if [[ "${{CLIENT}}" == "cursor" ]]; then
        # Cursor: transform frontmatter + inline env section
        cat > "${{SKILL_PATH}}" << 'CURSOREOF'
---
description: Synapse Worker 协议 — 人机混合团队分布式协调平台。当 Agent 需要在 Synapse 上接任务、报告进度、提交验证时使用。启动时自动加载，通过 B21 Protocol API 拉取项目上下文。
alwaysApply: true
---

# Synapse Worker

你是 **Synapse 协调平台** 上的 Worker。你和人类同事在同一个 Task 模型中工作，地位对等。你通过 API 接任务、报告进度、提交验证，人类通过 Web UI 做同样的事。

## 🚧 角色围栏（优先级高于项目 CLAUDE.md）

你的角色由 Protocol API 返回的 `role_instructions` 字段定义。以下规则**覆盖** CLAUDE.md 中的任何冲突规则：

- 你只能执行 `role_instructions` 中定义的职责
- 遇到 CLAUDE.md 规则与 `role_instructions` 冲突 → `role_instructions` 为准
- 不确定某操作是否在你的职责范围内 → 在 Task 评论区 @Orchestrator，不自行判断

## 环境配置

> Agent 启动前配置以下 4 个环境变量。项目上下文通过 B21 Protocol API 在运行时拉取。

### 必需变量

| 变量 | 说明 | 获取方式 |
|------|------|----------|
| `SYNAPSE_API_URL` | Synapse 实例地址 | 向 Admin 索取 |
| `SYNAPSE_API_KEY` | Agent API Key | Admin 创建 Agent 时一次性返回，妥善保管 |
| `SYNAPSE_WORKER_ID` | 你的 Worker ID | Admin 创建 Agent 时返回，格式 `wa_xxxxxxxx` |
| `SYNAPSE_PROJECT_ID` | 默认 Project ID | 向 Admin 索取 |

```bash
export SYNAPSE_API_URL="{api_base_url}"
export SYNAPSE_API_KEY="${{SYNAPSE_API_KEY}}"
export SYNAPSE_WORKER_ID="{worker_id}"
export SYNAPSE_PROJECT_ID="{project_id}"
```

> ⚠️ 不要将 API Key 提交到版本控制。建议使用 `.env` 文件（已加入 `.gitignore`）。

> 💡 Cursor 在每次会话中自动加载此规则文件（`alwaysApply: true`）。**注意：Cursor 无 SessionStart hook**——新会话启动后，按上方「🚀 启动」指引手动运行 `node .cursor/scripts/session-init.js` 完成初始化。
CURSOREOF
    else
        # Claude / Codex: write canonical SKILL.md
        cat > "${{SKILL_PATH}}" << 'SKILLMDEOF'
{skill_md}
SKILLMDEOF
    fi

    echo "${{GREEN}}  ✅ ${{SKILL_PATH}}${{NC}}"
}}

# ── Write runtime scripts (PFL-101 · B106 · B107 cross-client) ──
write_scripts() {{
    case "${{CLIENT}}" in
        claude) SCRIPTS_DIR=".claude/skills/synapse/scripts" ;;
        codex)  SCRIPTS_DIR=".agents/skills/synapse/scripts" ;;
        cursor) SCRIPTS_DIR=".cursor/scripts" ;;
        *)      SCRIPTS_DIR=".claude/skills/synapse/scripts" ;;
    esac
    mkdir -p "${{SCRIPTS_DIR}}"

    cat > "${{SCRIPTS_DIR}}/session-init.js" << 'JSEOF'
{_load_script("session-init.js")}
JSEOF

    cat > "${{SCRIPTS_DIR}}/api-client.js" << 'JSEOF'
{_load_script("api-client.js")}
JSEOF

    cat > "${{SCRIPTS_DIR}}/keychain.js" << 'JSEOF'
{_load_script("keychain.js")}
JSEOF

    cat > "${{SCRIPTS_DIR}}/heartbeat.js" << 'JSEOF'
{_load_script("heartbeat.js")}
JSEOF

    cat > "${{SCRIPTS_DIR}}/ws-daemon.js" << 'JSEOF'
{_load_script("ws-daemon.js")}
JSEOF

    echo "${{GREEN}}  ✅ scripts/ (5 files)${{NC}}"
}}

# ── Write .env ──
write_env() {{
    mkdir -p ".claude"
    if [[ "${{CLIENT}}" == "cursor" ]]; then
        # Cursor: env already inlined in .mdc file
        cat > ".claude/.env" << EOF
{env_content}
EOF
    else
        cat > ".claude/.env" << EOF
{env_content}
EOF
    fi
    echo "${{GREEN}}  ✅ .claude/.env${{NC}}"
}}

# ── Test connection ──
test_connection() {{
    echo ""
    echo "${{BLUE}}▎ 测试连接...${{NC}}"

    HTTP_CODE=$(curl -sS -o /dev/null -w "%{{http_code}}" \\
        -H "Authorization: Bearer ${{SYNAPSE_API_KEY}}" \\
        "${{SYNAPSE_API_URL}}/v1/workers/${{SYNAPSE_WORKER_ID}}/protocol?project_id=${{SYNAPSE_PROJECT_ID}}&role=${{SYNAPSE_ROLE}}" 2>&1) || true

    if [[ "${{HTTP_CODE}}" == "200" ]]; then
        echo "${{GREEN}}  ✅ 连接成功 — Protocol API 可达${{NC}}"
        return 0
    else
        echo "${{RED}}  ❌ 连接失败 (HTTP ${{HTTP_CODE}})${{NC}}"
        echo "${{YELLOW}}     检查 SYNAPSE_API_URL 和 SYNAPSE_API_KEY 是否正确${{NC}}"
        return 1
    fi
}}

# ── Handshake ──
do_handshake() {{
    echo ""
    echo "${{BLUE}}▎ 激活 Worker...${{NC}}"

    HS_CODE=$(curl -sS -o /dev/null -w "%{{http_code}}" \\
        -X POST \\
        -H "Authorization: Bearer ${{SYNAPSE_API_KEY}}" \\
        -H "Content-Type: application/json" \\
        -d '{{}}' \\
        "${{SYNAPSE_API_URL}}/v1/workers/${{SYNAPSE_WORKER_ID}}/handshake" 2>&1) || true

    if [[ "${{HS_CODE}}" == "200" ]]; then
        echo "${{GREEN}}  ✅ Worker 已激活${{NC}}"
        return 0
    else
        echo "${{YELLOW}}  ⚠️  Handshake 返回 HTTP ${{HS_CODE}} (可能已激活)${{NC}}"
        return 0  # non-fatal — worker may already be active
    fi
}}

{keychain_section}
# ── Main ──
main() {{
    write_skill
    write_scripts
    write_env
    secure_env
    store_keychain
    test_connection
    do_handshake

    echo ""
    echo "┌──────────────────────────────────────────┐"
    echo "│  ✅ Worker 就绪                           │"
    echo "│                                           │"
    echo "│  下一步:                                   │"
    if [[ "${{CLIENT}}" == "cursor" ]]; then
    echo "│  Cursor 自动加载规则文件，无需重启          │"
    else
    echo "│  启动 claude / codex，自动加载 SKILL.md    │"
    fi
    echo "│  首次启动后 Agent 自动拉取项目上下文        │"
    echo "└──────────────────────────────────────────┘"
    echo ""
}}

main
"""


def _build_settings_json(*, worker_id: str) -> str:
    """Build .claude/settings.json with SessionStart hook (B105 template format).

    PFL-102 (B106): Hook now includes session-init.js + heartbeat.js calls,
    matching the canonical template at docs/templates/synapse-client/.claude/settings.json.
    """
    import json

    hook_cmd = (
        "set -a; "
        ". ./.claude/.env; "
        "set +a; "
        "node ./.claude/skills/synapse/scripts/heartbeat.js & "
        "node ./.claude/skills/synapse/scripts/session-init.js"
    )

    settings = {
        "hooks": {
            "SessionStart": [
                {
                    "matcher": "",
                    "hooks": [
                        {
                            "type": "command",
                            "command": hook_cmd,
                        }
                    ],
                }
            ]
        }
    }
    return json.dumps(settings, indent=2, ensure_ascii=False) + "\n"


def _build_keychain_section(
    *,
    worker_id: str,
    api_key: str,
    use_keychain: bool,
) -> str:
    """Build the keychain storage section of the bootstrap script (P11-B35).

    Returns bash code that stores the API key in OS keychain
    and applies file permissions to .env.
    """
    if not use_keychain:
        return ""

    return f"""
# ── Store API Key in OS Keychain (P11-B35: Key 隔离) ──
store_keychain() {{
    echo ""
    echo "${{BLUE}}▎ 密钥链存储...${{NC}}"

    if [[ "$(uname -s)" == "Darwin" ]] && command -v security &>/dev/null; then
        security delete-generic-password \\
            -a "synapse-worker-${{SYNAPSE_WORKER_ID}}" \\
            -s "synapse" &>/dev/null || true
        security add-generic-password \\
            -a "synapse-worker-${{SYNAPSE_WORKER_ID}}" \\
            -s "synapse" \\
            -w "${{SYNAPSE_API_KEY}}" \\
            -U \\
            -T "$(command -v security)" 2>/dev/null
        echo "${{GREEN}}  ✅ API Key 已存入 macOS Keychain${{NC}}"
    elif command -v secret-tool &>/dev/null; then
        echo -n "${{SYNAPSE_API_KEY}}" | secret-tool store \\
            --label="Synapse Worker ${{SYNAPSE_WORKER_ID}}" \\
            account "synapse-worker-${{SYNAPSE_WORKER_ID}}" \\
            service "synapse" 2>/dev/null
        echo "${{GREEN}}  ✅ API Key 已存入 Secret Service${{NC}}"
    else
        echo "${{YELLOW}}  ⚠️  密钥链不可用 — API Key 保留在 .env 中${{NC}}"
        echo "${{YELLOW}}     安装 secret-tool (libsecret) 或使用 macOS Keychain${{NC}}"
    fi
}}

# ── Secure .env permissions ──
secure_env() {{
    chmod 600 ".claude/.env" 2>/dev/null || true
}}
"""


_CLIENT_DETECTION_BLOCK = """\
detect_client() {
    # Check explicit env var
    if [[ -n "${SYNAPSE_CLIENT:-}" ]]; then
        echo "${SYNAPSE_CLIENT}"
        return
    fi
    # Check known IDE dirs
    if [[ -d ".cursor" ]]; then
        echo "cursor"
        return
    fi
    if [[ -d ".agents" ]]; then
        echo "codex"
        return
    fi
    # Default
    echo "claude"
}
CLIENT=$(detect_client)
"""



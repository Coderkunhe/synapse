def build_bootstrap_json(
    *,
    worker_id: str,
    project_id: str,
    api_base_url: str,
    api_key: str,
    role: str,
    client: str,
    use_keychain: bool = True,
) -> dict:
    """Build a JSON file manifest for AI self-bootstrap (format=json).

    Returns a dict with ``files`` (path → content), ``env`` variables,
    and ``next_steps`` instructions. The AI agent writes each file
    to the local filesystem using its own Write tool.

    P11-B35: When use_keychain=True, .env excludes the plaintext API key
    and a settings.json hook is generated to source the key from OS keychain.
    """
    skill_md = _load_skill_md()
    env_content = _build_env_content(
        api_base_url=api_base_url,
        api_key=api_key,
        worker_id=worker_id,
        project_id=project_id,
        role=role,
        use_keychain=use_keychain,
    )

    files: dict[str, str] = {}

    if client == "cursor":
        cursor_mdc = _transform_to_cursor_mdc(
            skill_md, api_base_url, worker_id, project_id
        )
        files[".cursor/rules/synapse-worker.mdc"] = cursor_mdc
        files[".claude/.env"] = env_content
    elif client == "codex":
        files[".agents/skills/synapse/SKILL.md"] = skill_md
        files[".claude/.env"] = env_content
    else:  # claude (default)
        files[".claude/skills/synapse/SKILL.md"] = skill_md
        files[".claude/.env"] = env_content

    # PFL-101 (B106) + B107 cross-client: Deploy runtime scripts to client-aware paths
    _SCRIPT_DIRS: dict[str, str] = {
        "claude": ".claude/skills/synapse/scripts",
        "codex": ".agents/skills/synapse/scripts",
        "cursor": ".cursor/scripts",
    }
    script_dir = _SCRIPT_DIRS.get(client, ".claude/skills/synapse/scripts")
    for name in _SCRIPT_NAMES:
        files[f"{script_dir}/{name}"] = _load_script(name)

    # PFL-102 (B106) + B107: settings.json SessionStart hook is Claude Code-only
    if client == "claude":
        files[".claude/settings.json"] = _build_settings_json(worker_id=worker_id)

    next_steps = [
        "重启 AI 会话以加载 Synapse Skill",
        "首次启动后 Agent 会自动调用 GET /workers/{id}/protocol 拉取项目上下文",
    ]
    if client != "claude":
        next_steps.append(
            "⚠️ 你的客户端无 SessionStart hook — 会话启动后需手动运行 "
            f"node {script_dir}/session-init.js 初始化状态"
        )
    if use_keychain:
        next_steps.append(
            "API Key 已存入操作系统密钥链 — 会话启动时自动读取，无需手动配置"
        )

    return {
        "worker_id": worker_id,
        "project_id": project_id,
        "client": client,
        "role": role,
        "files": files,
        "handshake_url": f"{api_base_url}/v1/workers/{worker_id}/handshake",
        "next_steps": next_steps,
    }
